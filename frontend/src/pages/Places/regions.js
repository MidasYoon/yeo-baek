// 주소("서울 종로구 …")에서 시·도 이름을 찾는다. 17개에 맞지 않으면 null (해외 등).
export function regionFromAddress(address) {
  const first = (address ?? '').trim().split(/\s+/)[0]
  if (REGIONS.includes(first)) return first
  return REGION_ALIASES[first] ?? null
}

